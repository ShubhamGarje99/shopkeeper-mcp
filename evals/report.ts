/**
 * Renders EVAL_REPORT.md from the latest saved results of every agent.
 * Only numbers present in evals/results/*.json are printed; anything not yet
 * run is shown as pending.
 */
import fs from "node:fs";
import { DEFAULT_LIVE_MODEL } from "./config.js";
import { loadAllResults, REPORT_FILE, type RunResults } from "./results.js";
import { SCENARIOS } from "./scenarios.js";

const MODE_ORDER: Record<RunResults["mode"], number> = { live: 0, oracle: 1, baseline: 2 };
const PENDING = "pending - run `npm run eval` with ANTHROPIC_API_KEY set";

const pct = (n: number, d: number) => (d === 0 ? "-" : `${Math.round((n / d) * 100)}%`);
const usd = (v: number | null) => (v === null ? "n/a" : `$${v.toFixed(v < 0.01 && v > 0 ? 4 : 2)}`);
const tokens = (r: RunResults) =>
  r.mode === "live" ? `${r.summary.inputTokens.toLocaleString("en-US")} / ${r.summary.outputTokens.toLocaleString("en-US")}` : "-";
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function sortRuns(runs: RunResults[]): RunResults[] {
  const baselineOrder = (r: RunResults) => (r.label === "baseline-naive" ? 0 : 1);
  return [...runs].sort((a, b) => MODE_ORDER[a.mode] - MODE_ORDER[b.mode] || baselineOrder(a) - baselineOrder(b) || a.label.localeCompare(b.label));
}

function summaryRow(r: RunResults): string {
  const s = r.summary;
  const passed = `**${s.scenariosPassedAllTrials}/${s.scenarios}**${r.subset ? " (subset)" : ""}`;
  return `| ${r.name} | ${r.model ?? "-"} | ${r.mode} | ${passed} | ${pct(s.trialPasses, s.trialTotal)} (${s.trialPasses}/${s.trialTotal}) | ${s.toolCalls} | ${tokens(r)} | ${usd(s.costUsd)} | ${r.startedAt.slice(0, 10)} |`;
}

function cell(r: RunResults | undefined, id: string): string {
  if (!r) return "pending";
  const sc = r.scenarios.find((x) => x.id === id);
  if (!sc) return "-";
  const n = sc.trials.length;
  if (n === 1) return sc.passCount === 1 ? "PASS" : "FAIL";
  return `${sc.passCount}/${n}`;
}

function detailTable(r: RunResults): string[] {
  const lines = [
    `### ${r.name}${r.model ? ` (${r.model}${r.effort ? `, effort ${r.effort}` : ""})` : ""}`,
    "",
    `Run ${r.startedAt} | commit ${r.gitSha ?? "unknown"} | ${r.trialsPerScenario} trial(s) per scenario | clock ${r.clock}`,
    "",
    "| Scenario | Category | Result | Failed assertions | Tool calls | Tokens (in/out) | Cost |",
    "|---|---|---|---|---|---|---|",
  ];
  for (const sc of r.scenarios) {
    const n = sc.trials.length;
    const result = n === 1 ? (sc.passCount === 1 ? "PASS" : "FAIL") : `${sc.passCount}/${n}`;
    const failed = [...new Set(sc.trials.flatMap((t) => t.failed))];
    const calls = sc.trials.map((t) => t.toolCalls.map((c) => `${c.name}${c.isError ? `!${c.errorCode ?? ""}` : ""}`).join(", ") || "none");
    const callsCell = n === 1 ? `${sc.trials[0]?.toolCalls.length ?? 0}: ${calls[0]}` : `avg ${(sc.trials.reduce((a, t) => a + t.toolCalls.length, 0) / n).toFixed(1)}`;
    const inTok = sc.trials.reduce((a, t) => a + (t.usage?.input_tokens ?? 0), 0);
    const outTok = sc.trials.reduce((a, t) => a + (t.usage?.output_tokens ?? 0), 0);
    const cost = sc.trials.some((t) => t.costUsd === null) ? null : sc.trials.reduce((a, t) => a + (t.costUsd ?? 0), 0);
    lines.push(
      `| \`${sc.id}\` | ${sc.category} | ${result} | ${failed.length ? esc(failed.join("; ")) : "-"} | ${esc(callsCell)} | ${r.mode === "live" ? `${inTok}/${outTok}` : "-"} | ${usd(cost)} |`,
    );
  }
  return lines;
}

export function renderReport(runs: RunResults[]): string {
  const sorted = sortRuns(runs);
  const live = sorted.filter((r) => r.mode === "live");
  const byLabel = new Map(sorted.map((r) => [r.label, r]));
  const oracle = byLabel.get("oracle");
  const naive = byLabel.get("baseline-naive");
  const noop = byLabel.get("baseline-noop");
  const checkNames = new Map((oracle?.scenarios ?? []).map((s) => [s.id, s.trials[0]?.checks.map((c) => c.name) ?? []]));
  const totalChecks = [...checkNames.values()].reduce((a, c) => a + c.length, 0);

  const out: string[] = [
    "# Eval Report - Shopkeeper MCP",
    "",
    "Generated by the harness in [`evals/`](evals/). Every number below comes from a saved run in `evals/results/*.json`; regenerate this file with `npm run eval:report`.",
    "",
    "## Summary",
    "",
    "| Agent | Model | Mode | Scenarios passed | Trial pass rate | Tool calls | Tokens in / out | Cost (USD) | Run date |",
    "|---|---|---|---|---|---|---|---|---|",
  ];
  if (live.length === 0) out.push(`| Claude agent (live) | ${DEFAULT_LIVE_MODEL} | live | ${PENDING} | - | - | - | - | - |`);
  for (const r of sorted) out.push(summaryRow(r));
  out.push(
    "",
    "- **Oracle** runs a scripted, known-good tool sequence for each scenario through the real server and is graded by the same graders. 15/15 shows the server and the graders agree.",
    "- **Baselines** show the graders discriminate: the no-op agent calls no tools; the naive agent fires the obvious tool for any order number it sees, with no judgement.",
    "- **Reading the baselines.** The naive agent passes the three literal one-step requests (refund 1042, ship 1107, invoice 1150) and three requests where the server's own guardrail stopped it (over-refund, skipping to 'delivered', duplicate invoice), so those pass only because the server is safe even with a careless client. It fails every scenario that needs judgement: the paired on-time order it refunds blindly, the already-refunded order, the idempotent retry it double-refunds, the read-only question it turns into a write, and every lookup or report.",
    "- **Claude (live)** is the real agent loop (Anthropic Messages API + MCP tools). It needs an API key and has not been run in this environment yet, so its numbers are pending.",
    "",
    "## Scenario matrix",
    "",
    `| # | Scenario | Category | Oracle | Naive | No-op | ${live.length ? live.map((r) => `Claude ${r.model}`).join(" | ") : "Claude (live)"} |`,
    `|---|---|---|---|---|---|${live.length ? live.map(() => "---|").join("") : "---|"}`,
  );
  SCENARIOS.forEach((s, i) => {
    const liveCells = live.length ? live.map((r) => cell(r, s.id)).join(" | ") : "pending";
    out.push(`| ${i + 1} | \`${s.id}\` | ${s.category} | ${cell(oracle, s.id)} | ${cell(naive, s.id)} | ${cell(noop, s.id)} | ${liveCells} |`);
  });

  out.push("", "## Live Claude results", "");
  if (live.length === 0) {
    out.push(
      `**${PENDING}.**`,
      "",
      "```bash",
      "cp .env.example .env            # then set ANTHROPIC_API_KEY=...",
      "npm run eval                    # default model: claude-sonnet-5-5, effort medium",
      "npm run eval -- --model claude-haiku-5-5 --trials 3",
      "npm run eval -- --only refund-late-delivery,over-refund-refused",
      "```",
      "",
      "Each live run records the full tool-call trace, final answer, token usage and cost per scenario, saves `evals/results/live-<model>.json`, and regenerates this report.",
    );
  } else {
    for (const r of live) out.push(...detailTable(r), "");
  }

  out.push("", "## Detailed results (no API key needed)", "");
  for (const r of sorted.filter((x) => x.mode !== "live")) out.push(...detailTable(r), "");

  out.push("## Scenarios and what is graded", "");
  if (totalChecks) out.push(`${SCENARIOS.length} scenarios, ${totalChecks} assertions in total. A scenario passes only if every assertion passes.`, "");
  SCENARIOS.forEach((s, i) => {
    out.push(`**${i + 1}. \`${s.id}\`** (${s.category}) - ${s.title}`, "", `> ${s.prompt}`, "", `Expected: ${s.expectation}`, "");
    const names = checkNames.get(s.id);
    if (names?.length) out.push(...names.map((n) => `- ${n}`), "");
  });

  out.push(
    "## Methodology",
    "",
    "- **Isolation.** Each scenario attempt gets a fresh copy of the deterministic seed database and its own server process (`node dist/index.js` over stdio, spoken to with the MCP SDK `Client`). The store clock is pinned (`SHOPKEEPER_NOW=2026-09-30T18:00:00Z`) so lateness and overdue math is reproducible.",
    "- **Agents.** All agents use the same traced tool session. The live agent turns MCP `tools/list` into Anthropic tool definitions and runs a manual tool-use loop (max 12 turns, effort `medium` by default, server-side refusal fallback on), using the MCP server's own `instructions` plus a short operator system prompt. The prompt contains no scenario-specific hints.",
    "- **Graders (no LLM judge).** Three independent sources: (1) final database state, diffed table-by-table against the untouched template (e.g. exactly one new refund row for 1042 equal to the order total; read-only scenarios must leave every table byte-identical); (2) the tool-call trace (required tools, forbidden tools such as any write tool on a read-only question, `get_order` before `issue_refund`, idempotency key reuse); (3) light checks on the final answer (mentions the expected amount within $1, the invoice number, every late order ID). Expected values are computed with SQL on the database, never copied from tool output.",
    "- **Metrics.** *Scenarios passed* counts scenarios where every trial passed (pass^k when `--trials k`). *Trial pass rate* is passed trials / total trials. Cost uses list prices per million tokens (Sonnet 5.5 $2 in / $10 out, Haiku 5.5 $0.10 / $0.50, Opus 5.5 $4 / $20), with cache writes at 1.25x and cache reads at 0.1x input.",
    "- **Limitations.** The eval is single-turn: the agent cannot ask a follow-up question and wait, so \"asking for clarification\" means ending its reply with the question. The answer checks are regexes and can miss unusual phrasings (they are lenient on purpose; state and trace checks carry most of the weight). 15 scenarios is a smoke-level benchmark, not a statistically strong one. Use `--trials` to measure run-to-run variance in live mode.",
    "",
  );
  return out.join("\n");
}

export function writeReport(): string {
  const md = renderReport(loadAllResults());
  fs.writeFileSync(REPORT_FILE, md);
  return REPORT_FILE;
}
